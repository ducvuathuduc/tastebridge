export type Dict = (typeof dict)["en"];
const Ctx = createContext<{ lang: Lang; t: Dict; setLang: (l: Lang) => void }>({ lang: "en", t: dict.en as Dict, setLang: () => {} });

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");
  useEffect(() => {
    const saved = (typeof window !== "undefined" && localStorage.getItem("tb-lang")) as Lang | null;
    if (saved === "vi" || saved === "en") setLangState(saved);
  }, []);
  useEffect(() => { document.documentElement.lang = lang; }, [lang]);
  const setLang = (l: Lang) => { setLangState(l); localStorage.setItem("tb-lang", l); };
  return <Ctx.Provider value={{ lang, t: dict[lang] as unknown as Dict, setLang }}>{children}</Ctx.Provider>;
}
export const useI18n = () => useContext(Ctx);
